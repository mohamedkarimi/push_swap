#include "libft.h"

long	ft_atoi(const char *str)
{
	size_t	i;
	int		s;
	long	result;

	i = 0;
	s = 1;
	result = 0;
	if (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			s = -1;
		i++;
	}
	while (str[i] && ft_isdigit(str[i]))
	{
		result = result * 10 + (str[i] - '0');
		i++;
	}
	return (result * s);
}
